MIGRATIONS: Final[tuple[tuple[LiteralString, ...], ...]] = (_V1,)
SCHEMA_VERSION: Final = len(MIGRATIONS)


def migrate(provider: ConnectionProvider) -> int:
    """Apply pending migrations; concurrent callers are serialized by an advisory lock."""
    with provider.transaction() as cursor:
        cursor.execute(_MIGRATION_LOCK)
        cursor.execute(_VERSION_TABLE)
        cursor.execute("SELECT COALESCE(MAX(version), 0) FROM goatbeat_schema_version")
        row = cursor.fetchone()
        current = int(str(row[0])) if row is not None else 0
        if current > SCHEMA_VERSION:
            raise ConfigurationError(
                f"the database schema is at version {current} but this release only knows "
                f"{SCHEMA_VERSION}: upgrade goatbeat-postgres before running it"
            )
        for version, statements in enumerate(MIGRATIONS[current:], start=current + 1):
            for statement in statements:
                cursor.execute(statement)
            cursor.execute("INSERT INTO goatbeat_schema_version (version) VALUES (%s)", [version])
    return SCHEMA_VERSION
